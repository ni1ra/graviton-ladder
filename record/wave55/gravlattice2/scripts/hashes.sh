#!/bin/bash
# writes HASHES.md: sha256 of every file in this lane folder except HASHES.md itself
cd "$(dirname "$0")/.."
{ echo "# HASHES: w55-gravlattice2"; echo; echo "sha256 of every file in this folder (generated by scripts/hashes.sh, $(TZ=Europe/Oslo date '+%Y-%m-%d %H:%M %Z'))."; echo; echo '```';
  find . -type f ! -name HASHES.md ! -path '*/__pycache__/*' | sort | xargs sha256sum; echo '```'; } > HASHES.md
